""" Per frame PCA feature visualisation. 

Regions are separated (colored) by projecting their embeddings onto the 3 axes generated by PCA.
"""

import logging

import torch
import torch.nn.functional as F
import matplotlib.cm as cm
import cv2
import numpy as np

from evals.video_classification_frozen.eval import init_model, make_dataloader
from evals.video_classification_frozen.utils import ClipAggregation

RESOLUTION: int = 224
DEVICE: str = "cuda" if torch.cuda.is_available() else "cpu"

MEAN: torch.Tensor = torch.tensor([0.485, 0.456, 0.406]).view(3, 1, 1)
STD: torch.Tensor = torch.tensor([0.229, 0.224, 0.225]).view(3, 1, 1)


def main() -> None:
    logging.basicConfig()
    logger = logging.getLogger()
    logger.setLevel(logging.INFO)

    # Initialise model
    encoder = init_model(
        crop_size=RESOLUTION,
        device=DEVICE,
        pretrained="/home/ubuntu/Desktop/lehack/models/vjepa/vitl16.pth.tar",
        model_name="vit_large",
        patch_size=16,
        tubelet_size=2,
        frames_per_clip=16,
        uniform_power=True,
        checkpoint_key="target_encoder",
        use_SiLU=False,
        tight_SiLU=False,
        use_sdpa=True
    )

    encoder = ClipAggregation(
        encoder,
        tubelet_size=2,
        attend_across_segments=True
    ).to(DEVICE)
    encoder.eval()

    for p in encoder.parameters():
        p.requires_grad = False

    # Initialise dataloader
    dataloader = make_dataloader(
        root_path=["/home/ubuntu/Desktop/lehack/datasets/something_something_v2/test_dataloader.csv"],
        batch_size=4,
        world_size=1,
        rank=0,
        dataset_type="VideoDataset",
        resolution=RESOLUTION,
        frames_per_clip=16,
        frame_step=1,
        num_segments=1,
        eval_duration=None,
        num_views_per_segment=1,
        allow_segment_overlap=True,
        training=False,
        num_workers=12,
        subset_file=None
    )

    num_videos = 0
    max_videos = 24
    for data in dataloader:
        # Load batch onto GPU
        clips_gpu = [[data[0][0][0].to(DEVICE, non_blocking=True)]]
        clip_indices = data[2][0].to(DEVICE, non_blocking=True)
        video_paths = data[3]

        clips_cpu = data[0][0][0]
        batch_size = clips_cpu.shape[0]

        # Forward pass
        with torch.inference_mode():
            with torch.autocast(device_type=DEVICE, dtype=torch.bfloat16):
                outputs = encoder(clips_gpu, clip_indices)

        # embeddings shape: [batch_size, num_tokens, embed_dim]
        embeddings = outputs[0]
        for i in range(batch_size):
            embedding = embeddings[i].float().cpu()
            clip = clips_cpu[i]

            grid = embedding.reshape(8, 14, 14, -1)

            flat = grid.reshape(-1, grid.shape[-1])
            flat = flat - flat.mean(0)
            _, _, V = torch.pca_lowrank(flat, q=3)
            maps = (grid.reshape(-1, grid.shape[-1]) @ V)[:, 0].reshape(8, 14, 14)

            maps = (maps - maps.min()) / (maps.max() - maps.min())

            T_out = clip.shape[1]
            maps = F.interpolate(maps[None, None], size=T_out, mode="trilinear", align_corners=False)[0, 0]

            name = video_paths[i].split("/")[-1].replace(".webm", "")
            writer = cv2.VideoWriter(f"visualise_{name}.mp4", cv2.VideoWriter.fourcc(*"mp4v"), 12, (RESOLUTION, RESOLUTION))

            for t in range(T_out):
                frame = (clip[:, t] * STD + MEAN).clamp(0, 1).permute(1, 2, 0).numpy()
                h = F.interpolate(
                    maps[t][None, None].float(), 
                    (RESOLUTION, RESOLUTION), 
                    mode="bilinear", 
                    align_corners=False
                )[0, 0].numpy()
                heat_rgb = cm.get_cmap("turbo")(h)[..., :3]
                blend = 0.5 * frame + 0.5 * heat_rgb
                bgr = (blend[:, :, ::-1] * 255).astype(np.uint8)
                writer.write(bgr)

            writer.release()
            logger.info(f"Saved to visualise_{name}.mp4")

            num_videos += 1
            if num_videos >= max_videos:
                return


if __name__ == "__main__":
    main()
